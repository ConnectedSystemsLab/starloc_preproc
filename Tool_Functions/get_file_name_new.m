function file_name = get_file_name( ...
    mon, ...
    day, ...
    hr, ...
    minu, ...
    sec, ...
    center_freq, ...
    bw)
% All .dat files are named strictly as 'mm_dd/time_freq_bw,dat'
freq_str = num2str(center_freq/1e9);
root_path = "/home/jidazhang/Desktop/usrp_data/";
date_path = num2str(mon)+"_"+num2str(day)+"/";
time_path = "time_"+num2str(hr)+"_"+num2str(minu)+"_"+num2str(sec)+"_";
freq_path = "freq_"+freq_str(1:2)+"_"+freq_str(4:end)+"G"+"_";
if floor(bw/1e6) ~= bw/1e6
    bw_path = "bw_"+num2str(bw/1e6)+"M";
else
    bw_path = "bw_"+num2str(bw/1e6)+".0M";
end

file_name = root_path+date_path+time_path...
    +freq_path+bw_path+".dat";
end

